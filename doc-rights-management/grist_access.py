def cmd_list(cur, args):
    res = resolve_resource(cur, args)
    groups = get_role_groups(cur, res)
    print(f"Access for {res['label']}:")
    for role in ROLE_GROUP_NAMES:
        if role not in groups:
            continue
        cur.execute(
            """SELECT l.display_email, u.name FROM group_users gu
               JOIN users u ON u.id = gu.user_id
               JOIN logins l ON l.user_id = u.id
               WHERE gu.group_id = %s ORDER BY l.email""",
            (groups[role],))
        members = cur.fetchall()
        # FIXME: Not true. The inheritance mecanism is much more complex.
        # 1. Inheritance can have up to 3 levels (org => ws => docs => teams)
        # 2. Inheritance can be limited using permissions (bitwise operations)
        cur.execute(
            """SELECT sg.name, sg.type FROM group_groups gg
               JOIN groups sg ON sg.id = gg.subgroup_id
               WHERE gg.group_id = %s""",
            (groups[role],))
        subgroups = cur.fetchall()
        print(f"  {role}:")
        for email, name in members:
            print(f"    - {email} ({name})")
        for name, gtype in subgroups:
            kind = "inherited group" if gtype == "role" else "team"
            print(f"    - [{kind}] {name}")
        if not members and not subgroups:
            print("    (empty)")


def cmd_set(cur, args):
    res = resolve_resource(cur, args)
    if args.role == "members" and res["kind"] != "org":
        raise Fatal("The 'members' role only exists for organisations.")
    user_id, display_email = find_user(cur, args.email)
    groups = get_role_groups(cur, res)

    # Remove the user from the resource's other role groups (a single direct
    # role per resource), then add them to the target group.
    other_group_ids = [gid for role, gid in groups.items()
                       if role != args.role and role != "guests"]
    if other_group_ids:
        cur.execute("DELETE FROM group_users WHERE user_id = %s AND group_id IN %s",
                    (user_id, tuple(other_group_ids)))
        demoted = cur.rowcount
    else:
        demoted = 0
    cur.execute(
        """INSERT INTO group_users (group_id, user_id) VALUES (%s, %s)
           ON CONFLICT DO NOTHING""",
        (groups[args.role], user_id))
    added = cur.rowcount

    repair_parents(cur, res)

    if added:
        verb = "added to role" if not demoted else "moved to role"
        print(f"{display_email} {verb} '{args.role}' on {res['label']}.")
    elif demoted:
        print(f"{display_email} moved to role '{args.role}' on {res['label']}.")
    else:
        print(f"{display_email} already had role '{args.role}' on {res['label']}; nothing to do.")


def cmd_remove(cur, args):
    res = resolve_resource(cur, args)
    user_id, display_email = find_user(cur, args.email)
    groups = get_role_groups(cur, res)

    # Safety check: never leave a resource without any owner.
    cur.execute(
        """SELECT count(*) FROM group_users
           WHERE group_id = %s AND user_id != %s""",
        (groups["owners"], user_id))
    remaining_owners = cur.fetchone()[0]
    cur.execute("SELECT 1 FROM group_users WHERE group_id = %s AND user_id = %s",
                (groups["owners"], user_id))
    is_owner = cur.fetchone() is not None
    if is_owner and remaining_owners == 0 and not args.force:
        raise Fatal(f"{display_email} is the last owner of {res['label']}. "
                    "Use --force to remove them anyway.")

    role_group_ids = [gid for role, gid in groups.items() if role != "guests"]
    if role_group_ids:
        cur.execute("DELETE FROM group_users WHERE user_id = %s AND group_id IN %s",
                    (user_id, tuple(role_group_ids)))
        removed = cur.rowcount

        repair_parents(cur, res)
    else:
        removed = 0

    if removed:
        print(f"Direct access of {display_email} removed from {res['label']}.")
    else:
        print(f"{display_email} had no direct access to {res['label']}; nothing to do.")
    print("Note: the user may keep access inherited from the parent org or "
          "workspace, or through a team (group of type 'team').")


def cmd_repair_guests(cur, args):
    res = resolve_resource(cur, args)
    if res["kind"] == "org":
        added, removed = repair_org_guests(cur, res["id"])
    elif res["kind"] == "workspace":
        added, removed = repair_workspace_guests(cur, res["id"])
        repair_org_guests(cur, res["org_id"])
    else:
        raise Fatal("repair-guests applies to --org or --workspace.")
    print(f"Guests group of {res['label']} repaired "
          f"(+{len(added)} / -{len(removed)} users).")


# ---------------------------------------------------------------------------

def add_resource_args(sub):
    sub.add_argument("--org", help="Target organisation (numeric id or domain)")
    sub.add_argument("--workspace", help="Target workspace (numeric id)")
    sub.add_argument("--doc", help="Target document (full id or url_id)")


def main():
    parser = argparse.ArgumentParser(
        description="Modifies Grist access rights directly in the PostgreSQL database.",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dsn", default="",
                        help="PostgreSQL connection string "
                             "(otherwise PG* environment variables)")
    parser.add_argument("--dry-run", action="store_true",
                        help="Simulate: run everything then roll back the transaction")
    parser.add_argument("-v", "--verbose", action="store_true",
                        help="Log every executed SQL query to stderr")
    parser.add_argument("--log-file",
                        help="Log every executed SQL query to this file")
    sub = parser.add_subparsers(dest="command", required=True)

    p_list = sub.add_parser("list", help="List the access rights of a resource")
    add_resource_args(p_list)

    p_set = sub.add_parser("set", help="Grant a role to a user "
                                       "(adds them or changes their role)")
    add_resource_args(p_set)
    p_set.add_argument("--email", required=True, help="The user's email")
    p_set.add_argument("--role", required=True, choices=ASSIGNABLE_ROLES,
                       help="Role to grant ('members': orgs only)")

    p_rm = sub.add_parser("remove", help="Remove all direct access of a user")
    add_resource_args(p_rm)
    p_rm.add_argument("--email", required=True, help="The user's email")
    p_rm.add_argument("--force", action="store_true",
                      help="Allow removing the last owner")

    p_repair = sub.add_parser("repair-guests",
                              help="Recompute the guests group of an org/workspace")
    add_resource_args(p_repair)

    args = parser.parse_args()
    setup_logging(args.verbose, args.log_file)

    logger.debug("Connecting to the database (dsn=%s)", args.dsn or "<PG* environment variables>")
    conn = psycopg2.connect(args.dsn, connection_factory=SqlLoggingConnection)
    conn.initialize(logger)
    try:
        with conn.cursor() as cur:
            {"list": cmd_list, "set": cmd_set, "remove": cmd_remove,
             "repair-guests": cmd_repair_guests}[args.command](cur, args)
        if args.dry_run:
            conn.rollback()
            logger.debug("ROLLBACK (dry-run)")
            print("[dry-run] Transaction rolled back, nothing was written.")
        else:
            conn.commit()
            logger.debug("COMMIT")
    except Fatal as e:
        conn.rollback()
        logger.debug("ROLLBACK (error: %s)", e)
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
    finally:
        conn.close()


if __name__ == "__main__":
    main()
