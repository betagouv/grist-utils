#!/usr/bin/env python3
"""
Direct management of Grist access rights in the PostgreSQL "home" database.

Lists, grants/changes or removes a user's access to a document, a workspace
or an organisation by directly manipulating the `groups`, `group_users` and
`acl_rules` tables — i.e. the equivalent of the
PATCH /api/{orgs,workspaces,docs}/:id/access endpoints in ApiServer.ts.

Data model (see documentation/database.md):
  - Each resource has role groups ('owners', 'editors', 'viewers', plus
    'members' for orgs and the automatically managed 'guests'), linked to
    the resource through the `acl_rules` table.
  - Granting a role to a user = inserting them into `group_users` for the
    matching group (and removing them from the resource's other role groups,
    since a user holds only one direct role per resource).
  - After any change on a doc or workspace, Grist "repairs" the `guests`
    groups of the parent resources (see _repairWorkspaceGuests and
    _repairOrgGuests in app/gen-server/lib/homedb/HomeDBManager.ts) so that
    users invited on a child resource can navigate down to it. This script
    reproduces that logic.

Examples:
  # List the access rights of a document (full id or url_id)
  ./grist_access.py --dsn "$DSN" list --doc 4gPu3Fj1zSKQ

  # Add someone to the owners of a document
  ./grist_access.py --dsn "$DSN" set --doc 4gPu3Fj1zSKQ --email alice@example.com --role owners

  # Demote someone to plain viewer on a workspace
  ./grist_access.py --dsn "$DSN" set --workspace 12 --email alice@example.com --role viewers

  # Remove all direct access to an organisation (numeric id or domain)
  ./grist_access.py --dsn "$DSN" remove --org my-team --email bob@example.com

  # Simulate without writing anything
  ./grist_access.py --dsn "$DSN" --dry-run set --doc 4gPu3Fj1zSKQ --email alice@example.com --role owners

  # Log every executed SQL query (to stderr and/or to a file)
  ./grist_access.py --dsn "$DSN" -v --log-file grist_access.log list --org testorg

The connection uses --dsn when provided, otherwise the usual libpq
environment variables (PGHOST, PGDATABASE, PGUSER, PGPASSWORD, ...).
"""

import argparse
import logging
import sys
import time

import psycopg2
import psycopg2.extras

logger = logging.getLogger("grist_access")

# Roles that can be assigned directly. 'guests' is excluded: it is managed
# automatically (repaired by this script just like by Grist itself).
ASSIGNABLE_ROLES = ("owners", "editors", "viewers", "members")
ROLE_GROUP_NAMES = ("owners", "editors", "viewers", "members", "guests")

# Special users (see app/common/UserAPI.ts): never added to guests groups
# (filterEveryone logic in UsersManager.ts).
EVERYONE_EMAIL = "everyone@getgrist.com"
ANONYMOUS_USER_EMAIL = "anon@getgrist.com"


class Fatal(Exception):
    pass


class SqlLoggingConnection(psycopg2.extras.MinTimeLoggingConnection):
    """Logs every executed query through psycopg2's built-in
    LoggingConnection/LoggingCursor mechanism (cursors from this connection
    automatically log the query actually sent to the server, with parameters
    interpolated — including the INSERTs generated by execute_values).
    Only the formatting is overridden."""

    def filter(self, msg, curs):
        if isinstance(msg, bytes):
            msg = msg.decode("utf-8", "replace")
        # curs.timestamp is set by MinTimeLoggingCursor before execution.
        elapsed_ms = (time.time() - curs.timestamp) * 1000
        return "SQL [%.1f ms, rowcount=%s] %s" % (elapsed_ms, curs.rowcount, msg)


def setup_logging(verbose, log_file):
    logger.handlers.clear()
    logger.setLevel(logging.DEBUG)
    logger.propagate = False
    fmt = logging.Formatter("%(asctime)s %(levelname)s %(message)s")
    if verbose:
        handler = logging.StreamHandler(sys.stderr)
        handler.setFormatter(fmt)
        logger.addHandler(handler)
    if log_file:
        handler = logging.FileHandler(log_file, encoding="utf-8")
        handler.setFormatter(fmt)
        logger.addHandler(handler)
    if not logger.handlers:
        logger.addHandler(logging.NullHandler())


# ---------------------------------------------------------------------------
# Resource and user resolution
# ---------------------------------------------------------------------------

def find_user(cur, email):
    """Returns (user_id, display_email) for a given email address."""
    cur.execute(
        """SELECT u.id, l.display_email FROM users u
           JOIN logins l ON l.user_id = u.id
           WHERE l.email = %s""",
        (email.strip().lower(),))
    row = cur.fetchone()
    if not row:
        raise Fatal(f"No user with email {email!r}. "
                    "The user must have logged in at least once "
                    "(or have been invited) to exist in the database.")
    return row[0], row[1]


def resolve_resource(cur, args):
    """Returns a dict describing the targeted resource:
    {kind: 'org'|'workspace'|'doc', id, label, org_id, workspace_id}."""
    selectors = [s for s in (args.org, args.workspace, args.doc) if s is not None]
    if len(selectors) != 1:
        raise Fatal("Specify exactly one resource: --org, --workspace or --doc.")

    if args.org is not None:
        if args.org.isdigit():
            cur.execute("SELECT id, name FROM orgs WHERE id = %s", (int(args.org),))
        else:
            cur.execute("SELECT id, name FROM orgs WHERE domain = %s", (args.org,))
        row = cur.fetchone()
        if not row:
            raise Fatal(f"Organisation not found: {args.org!r} (id or domain).")
        return {"kind": "org", "id": row[0], "label": f"org #{row[0]} ({row[1]})",
                "org_id": row[0], "workspace_id": None}

    if args.workspace is not None:
        if not args.workspace.isdigit():
            raise Fatal("--workspace expects a numeric id.")
        cur.execute(
            """SELECT w.id, w.name, w.org_id, o.name FROM workspaces w
               JOIN orgs o ON o.id = w.org_id WHERE w.id = %s""",
            (int(args.workspace),))
        row = cur.fetchone()
        if not row:
            raise Fatal(f"Workspace not found: {args.workspace}.")
        return {"kind": "workspace", "id": row[0],
                "label": f"workspace #{row[0]} ({row[1]}) in org ({row[3]})",
                "org_id": row[2], "workspace_id": row[0]}

    # Document: full id or url_id.
    cur.execute(
        """SELECT d.id, d.name, d.workspace_id, w.org_id FROM docs d
           JOIN workspaces w ON w.id = d.workspace_id
           WHERE d.id = %s OR d.url_id = %s""",
        (args.doc, args.doc))
    rows = cur.fetchall()
    if not rows:
        raise Fatal(f"Document not found: {args.doc!r} (id or url_id).")
    if len(rows) > 1:
        ids = ", ".join(r[0] for r in rows)
        raise Fatal(f"Several documents match {args.doc!r}: {ids}. "
                    "Use the full id.")
    row = rows[0]
    return {"kind": "doc", "id": row[0], "label": f"doc {row[0]} ({row[1]})",
            "org_id": row[3], "workspace_id": row[2]}


def get_role_groups(cur, res):
    """Returns {role_name: group_id} for the resource's role groups."""
    column = {"org": "org_id", "workspace": "workspace_id", "doc": "doc_id"}[res["kind"]]
    cur.execute(
        f"""SELECT g.name, g.id FROM acl_rules a
            JOIN groups g ON g.id = a.group_id
            WHERE a.{column} = %s AND g.type = 'role'""",
        (res["id"],))
    groups = dict(cur.fetchall())
    missing = [r for r in ("owners", "editors", "viewers") if r not in groups]
    if missing:
        raise Fatal(f"Missing role groups for {res['label']}: {missing}. "
                    "The resource looks corrupted or nonexistent.")
    return groups


# ---------------------------------------------------------------------------
# Guests group repair (mirrors HomeDBManager)
# ---------------------------------------------------------------------------

def _special_user_ids(cur):
    cur.execute("SELECT l.email, u.id FROM users u JOIN logins l ON l.user_id = u.id "
                "WHERE l.email IN (%s, %s)", (EVERYONE_EMAIL, ANONYMOUS_USER_EMAIL))
    found = dict(cur.fetchall())
    return found.get(EVERYONE_EMAIL), found.get(ANONYMOUS_USER_EMAIL)


def _filter_everyone(cur, user_ids):
    """Replicates UsersManager.filterEveryone: removes the 'everyone@' user
    unless 'anon@' is present."""
    everyone_id, anon_id = _special_user_ids(cur)
    if anon_id is not None and anon_id in user_ids:
        return user_ids
    return {u for u in user_ids if u != everyone_id}


def _set_group_users(cur, group_id, target_user_ids):
    """Aligns the group's members with target_user_ids. Returns (added, removed)."""
    cur.execute("SELECT user_id FROM group_users WHERE group_id = %s", (group_id,))
    current = {r[0] for r in cur.fetchall()}
    to_add = target_user_ids - current
    to_remove = current - target_user_ids
    if to_remove:
        cur.execute("DELETE FROM group_users WHERE group_id = %s AND user_id in %s",
                    (group_id, tuple(to_remove)))
    if to_add:
        psycopg2.extras.execute_values(
            cur, "INSERT INTO group_users (group_id, user_id) VALUES %s",
            [(group_id, u) for u in to_add])
    return to_add, to_remove


def repair_workspace_guests(cur, workspace_id):
    """The workspace's guests group = direct users of the workspace's
    non-deleted docs (see _repairWorkspaceGuests)."""
    cur.execute(
        """SELECT g.id FROM acl_rules a JOIN groups g ON g.id = a.group_id
           WHERE a.workspace_id = %s AND g.name = 'guests'""", (workspace_id,))
    row = cur.fetchone()
    if not row:
        raise Fatal(f"Guests group not found for workspace {workspace_id}.")
    guest_group_id = row[0]
    cur.execute(
        """SELECT DISTINCT gu.user_id
           FROM docs d
           JOIN acl_rules a ON a.doc_id = d.id
           JOIN group_users gu ON gu.group_id = a.group_id
           WHERE d.workspace_id = %s AND d.removed_at IS NULL""",
        (workspace_id,))
    users = _filter_everyone(cur, {r[0] for r in cur.fetchall()})
    return _set_group_users(cur, guest_group_id, users)


def repair_org_guests(cur, org_id):
    """The org's guests group = direct users of the org's non-deleted
    workspaces, including the workspaces' guests groups
    (see _repairOrgGuests — must be called AFTER repair_workspace_guests)."""
    cur.execute(
        """SELECT g.id FROM acl_rules a JOIN groups g ON g.id = a.group_id
           WHERE a.org_id = %s AND g.name = 'guests'""", (org_id,))
    row = cur.fetchone()
    if not row:
        raise Fatal(f"Guests group not found for org {org_id}.")
    guest_group_id = row[0]
    cur.execute(
        """SELECT DISTINCT gu.user_id
           FROM workspaces w
           JOIN acl_rules a ON a.workspace_id = w.id
           JOIN group_users gu ON gu.group_id = a.group_id
           WHERE w.org_id = %s AND w.removed_at IS NULL""",
        (org_id,))
    users = _filter_everyone(cur, {r[0] for r in cur.fetchall()})
    return _set_group_users(cur, guest_group_id, users)


def repair_parents(cur, res):
    """Repairs the parents' guests groups after a change, in the same order
    as HomeDBManager (workspace first, then org)."""
    if res["kind"] == "doc":
        repair_workspace_guests(cur, res["workspace_id"])
        repair_org_guests(cur, res["org_id"])
    elif res["kind"] == "workspace":
        repair_org_guests(cur, res["org_id"])
    # Nothing to repair above an org.


